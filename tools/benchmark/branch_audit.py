#!/usr/bin/env python3
"""Count static branches and local labels in benchmark assembly variants.

Also verify that local branch targets exist and count unconditional jumps to
the next textual instruction. Assembler-inserted alignment padding is outside
these source counts. Output belongs in results/ or build/, never docs/.
"""
import argparse
import csv
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
CONDITIONAL = {'beq', 'bne', 'blt', 'bge', 'bltu', 'bgeu', 'beqz', 'bnez',
               'ble', 'bgt', 'bleu', 'bgtu', 'bgez', 'bltz', 'blez', 'bgtz'}


def audit(directory):
    rows = []
    for assembly in sorted(directory.glob('*.s')):
        text = assembly.read_text()
        labels, instructions = {}, []
        for line in text.splitlines():
            label = re.fullmatch(r'(\.L[^:\s]+):(?:\s*#.*)?', line.strip())
            if label:
                name = label[1]
                if name in labels:
                    raise ValueError(f'{assembly}: duplicate local symbol {name}')
                labels[name] = len(instructions)
            match = re.match(r'^\s+([a-z][a-z0-9.]*)\b\s*(.*)', line)
            if match:
                instructions.append((match[1], match[2].split('#')[0].strip()))
        jumps = conditional = next_jumps = 0
        for index, (op, operands) in enumerate(instructions):
            if op != 'j' and op not in CONDITIONAL:
                continue
            jumps += op == 'j'
            conditional += op in CONDITIONAL
            target = operands.split(',')[-1].strip()
            if target.startswith('.L'):
                if target not in labels:
                    raise ValueError(f'{assembly}: undefined local target {target}')
                next_jumps += op == 'j' and labels[target] == index + 1
        rows.append(dict(case=assembly.stem, instructions=len(instructions), jumps=jumps,
                         conditional=conditional, branches=jumps + conditional,
                         next_jumps=next_jumps, local_labels=len(labels),
                         numeric_labels=sum(bool(re.fullmatch(r'\.L\d+', label)) for label in labels),
                         generator_signature=text.startswith('# Generated by the Sakura compiler.\n')))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('run', type=pathlib.Path)
    parser.add_argument('--variants', nargs='+', default=['before', 'after'])
    parser.add_argument('--out', required=True, type=pathlib.Path, help='JSON/CSV output prefix')
    args = parser.parse_args()
    out = args.out.resolve()
    if out == ROOT / 'docs' or ROOT / 'docs' in out.parents:
        parser.error('comparison results belong in results/ or build/, not docs/')
    rows, totals = [], {}
    for variant in args.variants:
        entries = audit(args.run / variant)
        rows += [dict(variant=variant, **entry) for entry in entries]
        keys = ['instructions', 'jumps', 'conditional', 'branches', 'next_jumps', 'local_labels', 'numeric_labels']
        totals[variant] = {key: sum(entry[key] for entry in entries) for key in keys}
        totals[variant]['cases'] = len(entries)
        totals[variant]['signed_cases'] = sum(entry['generator_signature'] for entry in entries)
        print(variant, json.dumps(totals[variant], sort_keys=True))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix('.json').write_text(json.dumps(dict(totals=totals, cases=rows), indent=2) + '\n')
    if rows:
        with out.with_suffix('.csv').open('w', newline='') as stream:
            writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)


if __name__ == '__main__':
    main()
